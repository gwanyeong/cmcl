"""
Build _data/impact_factors.yaml from a Journal Citation Reports export.

Usage (from the repository root):
    pip install openpyxl pyyaml
    python _jcr/make_impact_factors.py JCR_2026.xlsx "JCR 2026"

For every journal that appears as a "publisher" in _data/citations.yaml it
stores the JIF and the best (smallest) "top X%" across all JCR categories the
journal belongs to, where top X% = category rank / journals in category.
"""

import html
import json
import re
import sys

import openpyxl
import yaml


def norm(name):
    name = html.unescape(str(name)).upper().replace("&", "AND")
    name = re.sub(r"^THE ", "", name)
    return re.sub(r"[^A-Z0-9]", "", name)


def title(category):
    words = category.title().split(" ")
    small = {"And", "Of", "In", "&"}
    return " ".join(w.lower() if w in small and i else w for i, w in enumerate(words))


def main(xlsx, edition):
    citations = yaml.safe_load(open("_data/citations.yaml", encoding="utf-8"))
    journals = sorted({html.unescape(c["publisher"]) for c in citations if c.get("publisher")})

    sheet = openpyxl.load_workbook(xlsx, read_only=True)["Journals"]
    header = next(sheet.iter_rows(max_row=1, values_only=True))
    col = {name: i for i, name in enumerate(header)}
    jif_col = next(name for name in header if str(name).endswith(" JIF") and "year" not in str(name))
    rows = {norm(r[col["Journal name"]]): r for r in sheet.iter_rows(min_row=2, values_only=True)}

    found, missing = [], []
    for journal in journals:
        row = rows.get(norm(journal))
        if not row:
            missing.append(journal)
            continue
        best = None
        for cat in json.loads(row[col["Category quartiles JSON"]] or "[]"):
            if not cat.get("jifRank"):
                continue
            rank, total = (int(x) for x in cat["jifRank"].split("/"))
            top = 100 * rank / total
            if best is None or top < best["top"]:
                best = {"top": top, "category": title(cat["category"]), "rank": cat["jifRank"]}
        entry = {"jif": str(row[col[jif_col]])}
        if best:
            entry.update(top=f"{best['top']:.1f}", category=best["category"], rank=best["rank"])
        found.append((journal, entry))

    found.sort(key=lambda x: float(x[1].get("top", 100)))
    lines = [
        "# Generated by _jcr/make_impact_factors.py -- rerun it when a new JCR is released.",
        '# Key = journal name exactly as it appears in citations.yaml "publisher".',
        "# top = best (smallest) rank / journals-in-category across the journal's JCR categories, in %.",
        "",
        f"edition: {edition}",
        "",
        "journals:",
    ]
    for journal, e in found:
        fields = ", ".join(f'{k}: "{v}"' for k, v in e.items())
        lines.append(f'  "{journal}": {{ {fields} }}')
    if missing:
        lines.append(f"  # not listed in {edition}:")
        lines += [f"  # {j}" for j in missing]
    open("_data/impact_factors.yaml", "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{len(found)} journals written, {len(missing)} not found: {missing}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "JCR")
